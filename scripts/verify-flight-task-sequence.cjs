const fs = require('fs');
const path = require('path');
const assert = require('node:assert/strict');
const ts = require('typescript');
const Module = require('module');
const React = require('react');
const {renderToStaticMarkup} = require('react-dom/server');
const root = path.resolve(__dirname, '..');
const file = path.join(root, 'components/poa/flight-task-sequence-editor.tsx');
const component = new Module(file, module);
component.filename = file;
component.paths = Module._nodeModulePaths(root);
component._compile(ts.transpileModule(fs.readFileSync(file,'utf8'), {compilerOptions:{module:ts.ModuleKind.CommonJS,jsx:ts.JsxEmit.ReactJSX,target:ts.ScriptTarget.ES2020}}).outputText,file);
const {moveFlightTask,FlightTaskSequenceEditor} = component.exports;
assert.deepEqual(moveFlightTask(['PA.IV.A','PA.IV.B'],'PA.IV.B','PA.IV.A'),['PA.IV.B','PA.IV.A']);
assert.deepEqual(moveFlightTask(['PA.IV.A'],'PA.IV.A'),['PA.IV.A']);
assert.deepEqual(moveFlightTask(['PA.IV.A'],'PA.IV.B'),['PA.IV.A','PA.IV.B']);
const library = ['A','B'].map((code) => ({acs_task_code_snapshot:`PA.IV.${code}`,task_name_snapshot:`Task ${code}`,area_name_snapshot:'Takeoffs',skill_elements_snapshot:[],examiner_notes:'',is_required:true,sort_order:10}));
const html = renderToStaticMarkup(React.createElement(FlightTaskSequenceEditor,{library,selected:['PA.IV.B','PA.IV.A'],onChange(){}}));
const list = html.slice(html.indexOf('<ol'),html.indexOf('</ol>'));
assert(list.indexOf('Task B') < list.indexOf('Task A'));
assert(html.includes('draggable="true"'));
assert(html.includes('Move up') && html.includes('Move down') && html.includes('Remove'));
const page = fs.readFileSync(path.join(root,'app/examiner/plan-of-action/generate/page.tsx'),'utf8');
assert(page.includes('["timeline", "flight_tasks", "compliance"]'));
assert(page.includes('coveredComplianceCodes.has(code) || selectedFlightComplianceCodes.has(code)'));
assert(page.includes('const generatedFlightTasks = selectedFlightTaskDrafts'));
assert(page.includes('sort_order: (index + 1) * 10'));
console.log('Flight-task checks passed: insertion, deduplication, manual sequence rendering, coverage integration, and saved selection.');
const readinessFile = path.join(root, 'lib/poa/generation-readiness.ts');
const readiness = new Module(readinessFile, module);
readiness._compile(ts.transpileModule(fs.readFileSync(readinessFile,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText,readinessFile);
const {hasCompleteTaskCoverage} = readiness.exports;
const required = ['PA.IV.A.K','PA.IV.A.R','PA.IV.A.S'];
assert.equal(hasCompleteTaskCoverage(required,new Set(['PA.IV.A.K','PA.IV.A.R'])),false);
assert.equal(hasCompleteTaskCoverage(required,new Set(['PA.IV.A.S'])),false);
assert.equal(hasCompleteTaskCoverage(required,new Set(required)),true);
assert.equal(hasCompleteTaskCoverage([],new Set()),false);
assert.equal(hasCompleteTaskCoverage(['CA.IV.A.K'],new Set(required)),false);
assert(page.includes('!allRatingTasksCovered ||'));
assert(!page.includes('Only checked questions will be included'));
console.log('Generation readiness checks passed: incomplete oral/flight coverage, empty requirements, and another rating remain disabled; complete coverage enables readiness.');
